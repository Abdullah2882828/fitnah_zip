import {NextResponse} from "next/server";
import {getSession} from "@/lib/session";
export const maxDuration=300;
export async function POST(r:Request){
 const s=await getSession(); if(!s)return NextResponse.json({error:"unauthorized"},{status:401});
 const {name,description,type,isPrivate,files}=await r.json();
 const gh=(p:string,method="GET",body?:any)=>fetch("https://api.github.com"+p,{method,headers:{Authorization:`Bearer ${s.token}`,Accept:"application/vnd.github+json","Content-Type":"application/json"},body:body?JSON.stringify(body):undefined});
 const priv=type==="website"?false:!!isPrivate; // websites are always public
 const c=await gh("/user/repos","POST",{name,description,private:priv,auto_init:true});
 const repo=await c.json(); if(!c.ok)return NextResponse.json({error:repo.errors?.[0]?.message||repo.message},{status:400});
 const base=`/repos/${repo.owner.login}/${repo.name}`;
 const ref=await (await gh(`${base}/git/ref/heads/${repo.default_branch}`)).json();
 const commit=await (await gh(`${base}/git/commits/${ref.object.sha}`)).json();
 const entries=Object.entries(files as Record<string,string>); const tree:any[]=[];
 for(let i=0;i<entries.length;i+=8){
  tree.push(...await Promise.all(entries.slice(i,i+8).map(async([path,content])=>{
   const b=await (await gh(`${base}/git/blobs`,"POST",{content,encoding:"utf-8"})).json();
   return {path:path.replace(/^\/+/,""),mode:"100644",type:"blob",sha:b.sha};})));
 }
 const t=await (await gh(`${base}/git/trees`,"POST",{base_tree:commit.tree.sha,tree})).json();
 const nc=await (await gh(`${base}/git/commits`,"POST",{message:"Generated by الفطنة",tree:t.sha,parents:[ref.object.sha]})).json();
 await gh(`${base}/git/refs/heads/${repo.default_branch}`,"PATCH",{sha:nc.sha});
 return NextResponse.json({url:repo.html_url});
}
